-- Run this SQL in Supabase SQL Editor.
-- Creates a shared table for warehouse screening reports.
create table if not exists public.warehouse_sites (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  site text not null,
  notes text,
  risk_score integer not null default 0,
  risk_label text not null,
  points jsonb not null default '{}'::jsonb,
  risk_checks jsonb not null default '{}'::jsonb,
  elevations_model_m jsonb
);

-- Prototype policy: public anonymous reads/inserts. Use only for non-sensitive
-- location data and a public demo. For production, add authentication and tighter RLS.
alter table public.warehouse_sites enable row level security;

create policy "Public can read warehouse screening records"
on public.warehouse_sites for select to anon using (true);

create policy "Public can insert warehouse screening records"
on public.warehouse_sites for insert to anon with check (true);

grant select, insert on public.warehouse_sites to anon;
grant usage, select on sequence public.warehouse_sites_id_seq to anon;
